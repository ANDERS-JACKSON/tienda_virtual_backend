-- Opciones de variante administradas por el admin (combo del vendedor)
-- y overrides por SKU (material, dimensiones, descripción corta).
-- Ejecutar una sola vez contra tienda_virtual_db.

CREATE TABLE IF NOT EXISTS xqm_catalogo.opcion_variante (
    opcion_variante_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             varchar(80)  NOT NULL,
    orden              integer      NOT NULL DEFAULT 0,
    activo             boolean      NOT NULL DEFAULT true
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_opcion_variante_nombre
    ON xqm_catalogo.opcion_variante (lower(nombre));

CREATE INDEX IF NOT EXISTS ix_opcion_variante_activo_orden
    ON xqm_catalogo.opcion_variante (activo, orden);

INSERT INTO xqm_catalogo.opcion_variante (nombre, orden, activo)
SELECT s.nombre, s.orden, true
FROM (VALUES
    ('Única', 1),
    ('Mini', 2),
    ('Pequeño', 3),
    ('Mediano', 4),
    ('Grande', 5),
    ('Extra grande', 6),
    ('Natural', 7),
    ('Multicolor', 8),
    ('Con caja de regalo', 9),
    ('Pack x2', 10)
) AS s(nombre, orden)
WHERE NOT EXISTS (
    SELECT 1 FROM xqm_catalogo.opcion_variante o
    WHERE lower(o.nombre) = lower(s.nombre)
);

ALTER TABLE xqm_catalogo.variante_producto
    ADD COLUMN IF NOT EXISTS opcion_variante_id integer NULL,
    ADD COLUMN IF NOT EXISTS material           varchar(200) NULL,
    ADD COLUMN IF NOT EXISTS dimensiones        varchar(200) NULL,
    ADD COLUMN IF NOT EXISTS descripcion_corta  varchar(150) NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_variante_producto_opcion'
    ) THEN
        ALTER TABLE xqm_catalogo.variante_producto
            ADD CONSTRAINT fk_variante_producto_opcion
            FOREIGN KEY (opcion_variante_id)
            REFERENCES xqm_catalogo.opcion_variante (opcion_variante_id)
            ON DELETE SET NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_variante_producto_opcion
    ON xqm_catalogo.variante_producto (opcion_variante_id);

-- Enlaza variantes existentes cuyo nombre coincide con una opción.
UPDATE xqm_catalogo.variante_producto v
SET opcion_variante_id = o.opcion_variante_id
FROM xqm_catalogo.opcion_variante o
WHERE v.opcion_variante_id IS NULL
  AND v.nombre IS NOT NULL
  AND lower(v.nombre) = lower(o.nombre);
