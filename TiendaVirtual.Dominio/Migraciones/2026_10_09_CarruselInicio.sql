-- Carrusel de imágenes del hero de inicio
CREATE TABLE IF NOT EXISTS xqm_configuracion.carrusel_inicio (
    carrusel_inicio_id int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    imagen_url         varchar(500) NOT NULL,
    titulo             varchar(120) NULL,
    subtitulo          varchar(300) NULL,
    enlace_url         varchar(500) NULL,
    texto_boton        varchar(80) NULL,
    activo             bool NOT NULL DEFAULT true,
    orden              int4 NOT NULL DEFAULT 0,
    CONSTRAINT pk_carrusel_inicio PRIMARY KEY (carrusel_inicio_id)
);

CREATE INDEX IF NOT EXISTS ix_carrusel_inicio_activo_orden
    ON xqm_configuracion.carrusel_inicio (activo, orden);
