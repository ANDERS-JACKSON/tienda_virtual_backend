-- Franjas visuales del inicio (fotos + enlace).
-- NO es el carrusel del hero (carrusel_inicio). Dos zonas:
--   campanas   → encima de Destacados ("Piezas en foco")
--   categorias → debajo de Destacados ("Compra por categoría")
-- Ejecutar una sola vez contra tienda_virtual_db.

CREATE TABLE IF NOT EXISTS xqm_configuracion.franja_inicio (
    franja_inicio_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zona             varchar(20)  NOT NULL,
    imagen_url       varchar(500) NOT NULL,
    titulo           varchar(80)  NULL,
    enlace_url       varchar(500) NOT NULL,
    activo           boolean      NOT NULL DEFAULT true,
    orden            integer      NOT NULL DEFAULT 0,
    CONSTRAINT ck_franja_inicio_zona CHECK (zona IN ('campanas', 'categorias'))
);

CREATE INDEX IF NOT EXISTS ix_franja_inicio_zona_activo_orden
    ON xqm_configuracion.franja_inicio (zona, activo, orden);
